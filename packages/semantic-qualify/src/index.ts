// QUALIFICATION BENCH — the exam a judge closure must sit before @gnldev/durable will run it.
//
// WHY THIS PACKAGE EXISTS: the same fixtures, the same prompt, two models — one answered 43% of the
// paraphrase pairs correctly, the other 100%. A judge is not a component you install, it is a
// component you MEASURE; without a number, "semantic v2 is enabled" says nothing about whether
// anything is protected. So the runtime refuses an uncertified judge, and this is where the
// certificate comes from.
//
// HONEST LIMITS, stated here because they belong next to the number they qualify:
//   * The fixtures are SYNTHETIC — generated pairs, not traffic. They measure whether a judge can
//     tell "same job, written differently" from "different job that looks alike"; they cannot tell
//     you how often either shape occurs in YOUR system. Live `precision@suspend` is the only answer
//     to that, and it stays the release gate.
//   * They were generated by a model of the same family as some of the judges you might test
//     ("twin brains"): a judge from that family may find its own family's phrasing easier than real
//     user text. Read a passing score as a floor on capability, not a promise of field accuracy.
//   * A published held-out set stops being held out the moment it is published. This certificate
//     stamps EXAM performance. Point it at your own fixtures (`--fixtures`) to measure something the
//     model cannot have seen.
//
// The bench evaluates BLIND: opaque ids, shuffled order, labels never sent to the judge, and the
// prompt is rendered by @gnldev/durable itself — the exam and production ask the identical question.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import {
  renderJudgePrompt, parseJudgeVerdict, JUDGE_PROMPT_VERSION,
  JUDGE_MIN_RECALL, JUDGE_MAX_FP, JUDGE_MIN_PAIRS,
} from '@gnldev/durable';
import type { JudgeCert } from '@gnldev/durable';
import { refuseUnknownNames } from '@gnldev/options';
import { QUALIFY_JUDGE_NAMES } from './option-names.js';

export interface FixturePair {
  id: string;
  toolName: string;
  a: string;
  b: string;
  /** 'dup-exact' | 'dup-paraphrase' → the same job; 'near-miss' | 'unrelated' → different jobs. */
  label: 'dup-exact' | 'dup-paraphrase' | 'near-miss' | 'unrelated';
}

export interface QualifyOptions {
  /** The SAME closure shape the runtime calls — transport only; the prompt comes from durable. */
  complete: (req: { system: string; user: string }) => Promise<string>;
  judgeModelId: string;
  /** Fixture files (absolute paths). Defaults to the two published sets. */
  fixtures?: string[];
  /** Pairs judged concurrently (default 4 — a bench should not look like an attack to a provider). */
  concurrency?: number;
  /**
   * Judge at most this many pairs, sampled EVENLY ACROSS LABELS.
   *
   * Exists because a slow judge makes the full set impractical: measured at 20 pairs in >10 minutes
   * on one hosted model, which puts the 600-pair default past two hours — long enough that the
   * honest choice becomes "skip the exam", and an unexamined judge is the thing this package refuses
   * to ship.
   *
   * It does NOT produce a cheaper certificate. `fixtureSetId` is derived from the pairs actually
   * judged, so a sampled run stamps a DIFFERENT set id than the full one, and every bar in the
   * report already prints its denominator. A 20-pair pass reads as a 20-pair pass.
   *
   * Sampling is per-label and in fixture order (not random): a limit that quietly dropped every
   * `near-miss` would report a perfect false-alarm rate measured against nothing — the same failure
   * the empty-bar gate exists to catch.
   *
   * THE PRACTICAL FLOOR IS 20 (five per label, see MIN_BAR_PAIRS). Below it the run still executes
   * and still reports, but it cannot pass: a rate over one or two pairs says nothing about the judge.
   * Measured before that gate existed: `--limit 4` earned a perfect judge a certificate on a
   * denominator of 1.
   */
  limit?: number;
  /** Progress line per completed pair. */
  onProgress?: (done: number, total: number) => void;
  now?: number;
}

export interface QualifyReport {
  judgeModelId: string;
  judgePromptVersion: string;
  fixtureSetId: string;
  total: number;
  /**
   * Per-label accuracy — the shape of the failure matters more than the average. `answered` counts
   * the pairs that came back as a parseable verdict; `n` counts the pairs that were PUT. They differ
   * whenever the judge errors or narrates, and the gap is what the coverage gates read.
   */
  byLabel: Record<string, { n: number; answered: number; correct: number; accuracy: number }>;
  paraphraseRecall: number;
  nearMissFp: number;
  /** Answers the judge did not phrase as one of the three words — these count as "no question". */
  unparsed: number;
  errors: number;
  passed: boolean;
  failureReasons: string[];
  /** Pairs the judge got wrong, so a failing run is diagnosable rather than just a verdict. */
  misses: Array<{ id: string; label: string; a: string; b: string; answered: string }>;
  cert?: JudgeCert;
}

/** Stable across machines and orderings: the hash identifies the CONTENT of the exam. */
export function fixtureSetIdOf(pairs: FixturePair[]): string {
  const canonical = pairs
    .map((p) => `${p.toolName}\u0000${p.a}\u0000${p.b}\u0000${p.label}`)
    .sort()
    .join('\u0001');
  return createHash('sha256').update(canonical).digest('hex').slice(0, 16);
}

export function loadFixtures(paths: string[]): FixturePair[] {
  const out: FixturePair[] = [];
  for (const p of paths) {
    const parsed = JSON.parse(readFileSync(p, 'utf8')) as { pairs?: FixturePair[] };
    if (!Array.isArray(parsed.pairs)) throw new Error(`@gnldev/semantic-qualify: ${p} has no "pairs" array`);
    for (const pair of parsed.pairs) {
      if (!pair.id || !pair.toolName || typeof pair.a !== 'string' || typeof pair.b !== 'string' || !pair.label) {
        throw new Error(`@gnldev/semantic-qualify: ${p} contains a pair missing id/toolName/a/b/label`);
      }
      out.push(pair);
    }
  }
  if (out.length === 0) throw new Error('@gnldev/semantic-qualify: no fixture pairs loaded');
  return out;
}

/** Deterministic shuffle (no Math.random): the order must not depend on when the bench was run. */
function blindOrder<T>(items: T[], seed: string): T[] {
  return items
    .map((item, i) => ({ item, k: createHash('sha256').update(`${seed}:${i}`).digest('hex') }))
    .sort((x, y) => (x.k < y.k ? -1 : 1))
    .map((x) => x.item);
}

const SAME_LABELS = new Set(['dup-exact', 'dup-paraphrase']);

/** At most `limit` pairs, taken round-robin across labels so no class is silently dropped. */
export function sampleEvenly(pairs: FixturePair[], limit?: number): FixturePair[] {
  if (!limit || limit <= 0 || limit >= pairs.length) return pairs;
  const byLabel = new Map<string, FixturePair[]>();
  for (const p of pairs) {
    const k = String((p as { label?: unknown }).label ?? '');
    const bucket = byLabel.get(k); if (bucket) bucket.push(p); else byLabel.set(k, [p]);
  }
  const buckets = [...byLabel.keys()].sort().map((k) => byLabel.get(k)!);
  const out: FixturePair[] = [];
  for (let i = 0; out.length < limit; i++) {
    let tookAny = false;
    for (const b of buckets) {
      if (i >= b.length) continue;
      out.push(b[i]!); tookAny = true;
      if (out.length === limit) break;
    }
    if (!tookAny) break;
  }
  return out;
}

/**
 * The smallest denominator at which a threshold is still a THRESHOLD.
 *
 * A bar is a rate, and a rate over a handful of pairs cannot land anywhere near its bar: with three
 * `dup-paraphrase` pairs the only scores available are 0, 0.333, 0.667 and 1.0, so a `>= 0.7`
 * requirement collapses into "be perfect" — the number stops describing the judge and starts
 * describing the sample. Below this floor a pass carries no information, and it is issued as a
 * CERTIFICATE, which is the form in which no-information travels furthest.
 *
 * Derived, not chosen: the floor is the smallest n that admits at least one passing score other than
 * a clean sweep. For `>= 0.7` that is 4 (3/4 = 0.75); one more is required so the bar can also be
 * MISSED by a single pair rather than only by a landslide. Measured before this existed: `--limit 4`
 * sampled one pair per label and a perfect judge earned a certificate on a denominator of 1.
 */
/** @gnldev/durable's JUDGE_MIN_PAIRS: the bench and the runtime check hold one number. */
const MIN_BAR_PAIRS = JUDGE_MIN_PAIRS;

export async function qualifyJudge(opts: QualifyOptions): Promise<QualifyReport> {
  refuseUnknownNames('qualifyJudge', opts, QUALIFY_JUDGE_NAMES);
  const paths = opts.fixtures ?? defaultFixturePaths();
  const pairs = sampleEvenly(loadFixtures(paths), opts.limit);
  const fixtureSetId = fixtureSetIdOf(pairs);
  // Blind: the judge sees the prompt the runtime renders and nothing else — no id, no label, no
  // fixture file, no neighbouring pair. Shuffling removes order as a signal.
  const order = blindOrder(pairs, fixtureSetId);

  const byLabel: QualifyReport['byLabel'] = {};
  const misses: QualifyReport['misses'] = [];
  let unparsed = 0;
  let errors = 0;
  let done = 0;

  const concurrency = Math.max(1, opts.concurrency ?? 4);
  const queue = [...order];
  const worker = async (): Promise<void> => {
    for (;;) {
      const p = queue.shift();
      if (!p) return;
      const { system, user } = renderJudgePrompt(p.toolName, p.a, p.b);
      let answered = '(error)';
      let verdict: ReturnType<typeof parseJudgeVerdict>;
      try {
        const raw = await opts.complete({ system, user });
        answered = String(raw ?? '').trim().slice(0, 40);
        verdict = parseJudgeVerdict(raw);
        if (verdict === undefined) unparsed++;
      } catch {
        errors++;
      }
      const expectSame = SAME_LABELS.has(p.label);
      // An unparsed or errored answer is NOT credited: at runtime it degrades to today's behavior,
      // so scoring it as a correct 'different' would flatter the judge for staying silent.
      const correct = verdict !== undefined && (verdict === 'same') === expectSame;
      const slot = (byLabel[p.label] ??= { n: 0, answered: 0, correct: 0, accuracy: 0 });
      slot.n++;
      if (verdict !== undefined) slot.answered++;
      if (correct) slot.correct++;
      else misses.push({ id: p.id, label: p.label, a: p.a, b: p.b, answered });
      opts.onProgress?.(++done, order.length);
    }
  };
  await Promise.all(Array.from({ length: concurrency }, worker));
  for (const slot of Object.values(byLabel)) slot.accuracy = slot.n ? slot.correct / slot.n : 0;

  // The two numbers the runtime enforces. Recall is measured on PARAPHRASE pairs only: 'dup-exact'
  // pairs are already caught by the deterministic layers, so crediting them would let a judge that
  // only recognises identical strings pass an exam about rewordings.
  const par = byLabel['dup-paraphrase'];
  const paraphraseRecall = par && par.n ? par.correct / par.n : 0;
  const nm = byLabel['near-miss'];
  // False alarm = a 'near-miss' pair the judge called the same job. Counted directly rather than as
  // 1-accuracy, because unparsed answers are not false alarms — they are silence.
  const nmMisses = misses.filter((m) => m.label === 'near-miss' && m.answered.trim().toUpperCase() === 'SAME').length;
  const nearMissFp = nm && nm.n ? nmMisses / nm.n : 0;

  const failureReasons: string[] = [];
  // COVERAGE BEFORE SCORE. Both bars are RATES, and a rate over zero pairs is 0 — which reads as a
  // perfect result and is in fact no result at all. Measured: a fixture set of 20 'dup-paraphrase'
  // pairs and nothing else scored a judge that answers 'SAME' to everything at recall 1.000,
  // false-alarm 0.000, PASSED, certificate issued — and validateJudgeConfig accepted it. That is the
  // exact "installed but not actually protecting anything" outcome this package exists to prevent,
  // reached through the door the docs themselves recommend (`--fixtures`, bring your own set: a user
  // whose logs contain real duplicates naturally writes a file of nothing but duplicates).
  // A bar nothing was measured against is a FAILURE, not a pass.
  // THE DIAGNOSIS COMES FIRST when it changes what you would do next. A judge that answered every
  // pair in prose scores recall 0.000 — identical, on the report, to a judge that answered wrongly
  // every time. The two call for opposite actions: one needs a different model, the other needs the
  // same model to stop reasoning out loud. Measured on a real provider: three hosted models, all
  // three unparseable, all three reported primarily as "recall below the bar" — which points at the
  // wrong fix.
  //
  // Half is the line because below it the bars still carry information, and above it they are noise.
  //
  // `push`, and the POSITION of this block is what puts the diagnosis first — deliberately, not by
  // accident. An `unshift` here would also reach the front, but it would make the position
  // meaningless: the block could drift anywhere in this function and the test asserting
  // `failureReasons[0]` would still pass. Measured both ways — with unshift, moving the block to the
  // bottom kept every test green; with push, it turns one red. The weaker call is the one that keeps
  // the ordering honest.
  // TRANSPORT FIRST, because it is one step more fundamental than format: an answer that never came
  // back cannot be badly worded. Same failure mode as the block below, different cause, and the
  // format gate does NOT cover it — `errors` and `unparsed` are separate counters, so a run that
  // errors on every call has `unparsed` near zero and slips past. Measured on a real provider: a
  // model that scored 20/20 on a sample was then run over the full 600 and returned 564 errors, all
  // of them rate limits; the report's headline read "paraphrase recall 0.047 < required 0.7", which
  // tells the operator to change a model that was in fact answering perfectly.
  if (order.length > 0 && errors / order.length > 0.5) {
    failureReasons.push(
      `${errors} of ${order.length} calls FAILED before an answer came back — this is a TRANSPORT `
      + 'failure (rate limit, timeout, auth), not a judgement one. The bars below are measured on the '
      + 'few calls that returned, so they describe the network, not the model. Check one raw response '
      + 'and the provider quota before changing model.',
    );
  }
  if (order.length > 0 && unparsed / order.length > 0.5) {
    failureReasons.push(
      `${unparsed} of ${order.length} answers could not be parsed as SAME / DIFFERENT / UNSURE — this is a `
      + 'FORMAT failure, not a judgement one. Reasoning models in particular narrate before answering, and '
      + 'the bars below are measured on the few answers that survived. Check a raw reply before changing model.',
    );
  }
  if (par?.n && par.n < MIN_BAR_PAIRS) {
    failureReasons.push(
      `paraphrase recall measured over only ${par.n} pair(s) — below ${MIN_BAR_PAIRS} the ${JUDGE_MIN_RECALL} bar `
      + 'admits no score between "perfect" and "failed", so passing it says nothing about the judge',
    );
  }
  // COVERAGE IS COUNTED IN ANSWERS, NOT IN ATTEMPTS — and only this bar needs the distinction.
  // Silence costs the judge its recall (an unparsed answer is never credited as correct above), so
  // there a silent judge is punished. Here it is REWARDED: a pair that came back as an error or as
  // prose produced no question, and a pair that produced no question cannot produce a false alarm.
  // It lands in the denominator as clean. Measured on the published fixtures: a judge that threw on
  // 149 of the 150 near-miss pairs scored accuracy 0.000 on that label and false alarm 0.007 — it
  // PASSED, the certificate was issued, and validateJudgeConfig accepted it at runtime. The bar the
  // certificate attests was never once exercised.
  // The RATE keeps its full denominator on purpose: it predicts what operators will actually see,
  // and silence really does produce no prompt. It is the COVERAGE that has to move.
  if (nm?.n && nm.answered < MIN_BAR_PAIRS) {
    const single = nm.answered > 0 ? (1 / nm.answered).toFixed(3) : 'undefined';
    failureReasons.push(
      `near-miss false alarm measured over only ${nm.answered} answered pair(s) of ${nm.n} put — `
      + (nm.answered < nm.n
        ? 'the rest were errors or unparseable replies, and silence cannot raise a false alarm, so it '
          + 'dilutes this bar towards a pass without ever testing it. '
        : '')
      + `Below ${MIN_BAR_PAIRS} answers a single wrong one is already ${single}, far past the `
      + `${JUDGE_MAX_FP} allowance, so the bar is pass-or-nothing`,
    );
  }
  if (!par?.n) {
    failureReasons.push("the fixture set contains no 'dup-paraphrase' pairs — recall cannot be measured, so it cannot be passed");
  }
  if (!nm?.n) {
    failureReasons.push("the fixture set contains no 'near-miss' pairs — the false-alarm bar cannot be measured, so a judge that answers SAME to everything would score 0.000 here");
  }
  if (!(paraphraseRecall >= JUDGE_MIN_RECALL)) {
    failureReasons.push(`paraphrase recall ${paraphraseRecall.toFixed(3)} < required ${JUDGE_MIN_RECALL}`);
  }
  if (!(nearMissFp <= JUDGE_MAX_FP)) {
    failureReasons.push(`near-miss false alarms ${nearMissFp.toFixed(3)} > allowed ${JUDGE_MAX_FP}`);
  }
  const passed = failureReasons.length === 0;

  return {
    judgeModelId: opts.judgeModelId,
    judgePromptVersion: JUDGE_PROMPT_VERSION,
    fixtureSetId,
    total: order.length,
    byLabel,
    paraphraseRecall,
    nearMissFp,
    unparsed,
    errors,
    passed,
    failureReasons,
    misses,
    ...(passed
      ? {
          cert: {
            v: 1 as const,
            fixtureSetId,
            judgeModelId: opts.judgeModelId,
            judgePromptVersion: JUDGE_PROMPT_VERSION,
            paraphraseRecall: Number(paraphraseRecall.toFixed(4)),
            nearMissFp: Number(nearMissFp.toFixed(4)),
            paraphrasePairs: par?.n ?? 0,
            nearMissAnswered: nm?.answered ?? 0,
            nearMissPairs: nm?.n ?? 0,
            passedAt: opts.now ?? Date.now(),
          },
        }
      : {}),
  };
}

/**
 * The two published sets, resolved relative to this package.
 *
 * @param base the module URL to resolve against. Defaults to this file and nothing in production
 *   passes it — it exists so the decoding below can be TESTED. Without it a test can only assert
 *   against the path this repository happens to be checked out at, which contains no space, so the
 *   percent-decoding bug reproduces on a user's machine and on nobody's CI. (Measured: the test
 *   written without this parameter stayed green with the fix reverted.)
 */
export function defaultFixturePaths(base: string = import.meta.url): string[] {
  const dir = new URL('../fixtures/', base);
  // fileURLToPath, NOT `.pathname`: a file URL is percent-ENCODED, and `.pathname` hands back the
  // encoding verbatim. Installed under a directory with a space in it — 'My Projects', or any of the
  // paths macOS and Windows hand out by default — the default bench resolved to
  // `.../My%20Projects/.../pairs-calibration.json` and died on ENOENT against a file that is right
  // there. (It also fixes the Windows drive-letter shape, where `.pathname` yields '/C:/...'.)
  return [
    fileURLToPath(new URL('pairs-calibration.json', dir)),
    fileURLToPath(new URL('pairs-holdout.json', dir)),
  ];
}

/** Human-readable bench output — the table an operator reads before trusting a number. */
export function formatReport(r: QualifyReport): string {
  const lines: string[] = [];
  lines.push(`judge: ${r.judgeModelId}   prompt: v${r.judgePromptVersion}   fixtures: ${r.fixtureSetId} (${r.total} pairs)`);
  lines.push('');
  for (const [label, s] of Object.entries(r.byLabel)) {
    lines.push(`  ${label.padEnd(16)} ${(s.accuracy * 100).toFixed(0).padStart(3)}%  (${s.correct}/${s.n})`);
  }
  lines.push('');
  // The DENOMINATOR is printed beside each bar, because a rate hides how much was weighed: '0.0%'
  // over 75 near-miss pairs and '0.0%' over 2 are the same three characters and completely different
  // evidence. (Zero pairs is now a failure outright, but a handful is still thin, and the operator is
  // the one who has to judge "thin" — they cannot if the report only shows them the percentage.)
  const n = (label: string): number => r.byLabel[label]?.n ?? 0;
  lines.push(`  paraphrase recall   ${(r.paraphraseRecall * 100).toFixed(1)}%   over ${n('dup-paraphrase')} pairs   (required >= ${(JUDGE_MIN_RECALL * 100).toFixed(0)}%)`);
  // Same reasoning, one turn further: on THIS bar silence is scored as "no alarm", so the pairs that
  // never came back are weightless — and printing only the pairs PUT would show a denominator the
  // judge was never asked to stand behind. When the two differ, both are printed.
  const nmAnswered = r.byLabel['near-miss']?.answered ?? 0;
  const nmSpan = nmAnswered === n('near-miss')
    ? `${nmAnswered} pairs`
    : `${nmAnswered} of ${n('near-miss')} pairs answered`;
  lines.push(`  near-miss false alarm ${(r.nearMissFp * 100).toFixed(1)}%   over ${nmSpan}   (allowed <= ${(JUDGE_MAX_FP * 100).toFixed(0)}%)`);
  if (r.unparsed) lines.push(`  unparsed answers    ${r.unparsed}  (counted as no-question, never as a correct 'different')`);
  if (r.errors) lines.push(`  errors              ${r.errors}`);
  lines.push('');
  lines.push(r.passed ? '  PASSED — certificate issued' : `  FAILED — ${r.failureReasons.join('; ')}`);
  if (!r.passed && r.misses.length) {
    lines.push('');
    lines.push('  sample misses:');
    for (const m of r.misses.slice(0, 8)) lines.push(`    [${m.label}] "${m.a}" | "${m.b}" → answered ${m.answered}`);
  }
  lines.push('');
  lines.push('  These fixtures are synthetic and published: this certificate stamps EXAM performance,');
  lines.push('  not field accuracy. Watch precision@suspend in Studio once the layer is live.');
  return lines.join('\n');
}
